"""
Build missing idea translations for i18n-data.js
Generates both en and zh translations for all missing idea entries.
"""
import json
import re

# Load data files
with open('data/philosophers.json', 'r', encoding='utf-8') as f:
    western = json.load(f)
with open('data/chinese-philosophers.json', 'r', encoding='utf-8') as f:
    chinese = json.load(f)

# Parse existing i18n-data.js
with open('js/i18n-data.js', 'r', encoding='utf-8') as f:
    content = f.read()

# Extract existing idea IDs
idea_start = content.index("  idea: {")
idea_end = content.index('  },', idea_start + 10)
idea_section = content[idea_start:idea_end]
existing_ids = set(re.findall(r"'([a-z]+\d+)'\s*:", idea_section))

# Collect all ideas
all_ideas = {}
for p in western:
    for idea in p['ideas']:
        all_ideas[idea['id']] = {
            'id': idea['id'],
            'text': idea['text'],
            'name': p['name'],
            'tradition': 'western',
        }
for p in chinese:
    for idea in p['ideas']:
        all_ideas[idea['id']] = {
            'id': idea['id'],
            'text': idea['text'],
            'name': p['name'],
            'tradition': 'chinese',
        }

# Find missing
missing = []
for idea_id in sorted(all_ideas.keys()):
    if idea_id not in existing_ids:
        missing.append(all_ideas[idea_id])

